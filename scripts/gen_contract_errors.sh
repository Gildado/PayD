#!/usr/bin/env bash
set -euo pipefail
# Extracts every error-enum variant and numeric code into docs/CONTRACT_ERRORS.md (issue #1751).
out=${1:-docs/CONTRACT_ERRORS.md}
{ echo "# Contract Error Codes"; echo; echo "Generated by \`scripts/gen_contract_errors.sh\` - do not edit by hand."; echo
for f in contracts/*/src/lib.rs; do
  rows=$(awk '/pub enum [A-Za-z]*Error \{/,/^\}/' "$f" | sed -n 's/^[[:space:]]*\([A-Za-z][A-Za-z0-9]*\) = \([0-9][0-9]*\),.*/| \2 | \1 |/p'); [ -n "$rows" ] || continue
  echo "## $(basename "$(dirname "$(dirname "$f")")")"; echo; echo "| Code | Variant |"; echo "|------|---------|"; echo "$rows"; echo
done
} > "$out"
